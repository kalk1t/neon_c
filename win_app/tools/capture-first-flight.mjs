// Read-only browser reference adapter; writes only into win_app.
import { readFile, writeFile, mkdir, copyFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';

const root=fileURLToPath(new URL('../',import.meta.url));
const browser=path.resolve(root,'../game');
const fromBrowser=(p)=>import(pathToFileURL(path.join(browser,p)).href);
const [{Car},{ROADS},{Track},THREE]=await Promise.all([
  fromBrowser('src/car.js'),fromBrowser('src/roads.js'),fromBrowser('src/track.js'),
  fromBrowser('node_modules/three/build/three.module.js')]);
const road=ROADS[0],track=new Track(road);
for(const dir of ['src/core','tests','reference/source-assets','assets/models','assets/brand','third_party/licenses']) await mkdir(path.join(root,dir),{recursive:true});
const f=(v)=>{if(!Number.isFinite(v))throw Error(`Nonfinite reference ${v}`);return v.toPrecision(17);};
await writeFile(path.join(root,'src/core/skyline_data.h'),
  `/* Generated from browser roads.js by tools/capture-first-flight.mjs. */\n#ifndef RR_SKYLINE_DATA_H\n#define RR_SKYLINE_DATA_H\n#define RR_SKYLINE_CONTROL_COUNT ${road.ctrl.length}\nstatic const RRVec3 rr_skyline_control[] = {\n${road.ctrl.map(p=>`    {${p.map(f).join(',')}}`).join(',\n')}\n};\nstatic const double rr_skyline_checkpoints[] = {${road.checkpoints.map(f).join(',')}};\n#endif\n`);

function referenceCar(){
  // Call the real browser Car methods, with only the rendering objects stubbed.
  const c=Object.create(Car.prototype);
  Object.assign(c,{pos:new THREE.Vector3(),vel:new THREE.Vector3(),fwd:new THREE.Vector3(0,0,-1),
    t:0,boost:1,boosting:false,maxMul:1,nitro:0,thrust:0,kick:0,sputter:0,
    model:{position:{},rotation:{}},pods:[],fans:[],ribbons:[],sync(){}});
  c.place(new THREE.Vector3(0,118,0),0,0);
  return c;
}
const cases=[
  {name:'thrust',frames:360,dt:1/60,input:()=>[1,0,0,0,0]},
  {name:'boost-drain-and-regen',frames:600,dt:1/60,input:i=>[1,0,0,0,i<360?1:0]},
  {name:'brake-reverse',frames:360,dt:1/60,input:i=>i<120?[1,0,0,0,0]:[0,1,0.4,-0.25,0]},
  {name:'turn-and-climb',frames:360,dt:1/30,input:i=>[1,i>240?0.7:0,Math.sin(i*0.02),Math.cos(i*0.017),i<60?1:0]},
  {name:'spin-left-and-right',frames:360,dt:1/60,input:()=>[1,0,-0.2,0.3,0],spin:i=>i===60?-1:i===240?1:0},
  {name:'high-refresh-coasting',frames:720,dt:1/144,input:i=>i<360?[0.65,0,-0.7,-0.5,0]:[0,0,0,0,0]},
  {name:'capped-long-frames',frames:180,dt:0.05,input:i=>[1,0,i<90?0.8:-0.8,i<90?0.6:-0.6,1]},
];
const rows=[];
for(const [scenario,spec] of cases.entries()){
  const c=referenceCar();
  for(let step=0;step<spec.frames;step++){
    const input=spec.input(step),spin=spec.spin?.(step)??0;
    if(spin)c.dodge(spin);
    c.update(spec.dt,{throttle:input[0],brake:input[1],steer:input[2],climb:input[3],boost:!!input[4]},{collide:()=>null});
    const expected=[c.pos.x,c.pos.y,c.pos.z,c.vel.x,c.vel.y,c.vel.z,c.yaw,c.pitch,c.roll,c.speed,c.boost,c.rollT,c.surge,c.thrust,c.nitro,c.stun];
    rows.push(`{${scenario},${f(spec.dt)},{${input.slice(0,4).map(f).join(',')},${input[4]?'true':'false'}},${spin},{${expected.map(f).join(',')}}}`);
  }
}
const curveRows=Array.from({length:81},(_,i)=>{
  const u=i/80,p=track.curve.getPoint(u),at=track.curve.getPointAt(u),tan=track.curve.getTangent(u);
  return `{${f(u)},{${[p.x,p.y,p.z].map(f)}},{${[at.x,at.y,at.z].map(f)}},{${[tan.x,tan.y,tan.z].map(f)}}}`;
});
await writeFile(path.join(root,'tests/generated_reference.h'),
  `/* Generated by actual browser Car/Track methods; do not hand-edit. */\nstatic const FlightFixture flight_fixtures[] = {\n${rows.join(',\n')}\n};\nstatic const CurveFixture curve_fixtures[] = {\n${curveRows.join(',\n')}\n};\nstatic const double reference_length=${f(track.length)};\nstatic const RRGate reference_gates[] = {\n${track.checkpoints.map(c=>`{{${[c.pos.x,c.pos.y,c.pos.z].map(f)}},{${[-Math.sin(c.yaw),0,-Math.cos(c.yaw)].map(f)}},${f(c.yaw)}}`).join(',\n')}\n};\n`);

await copyFile(path.join(browser,'public/models/car.glb'),path.join(root,'reference/source-assets/roadster.glb'));
await copyFile(path.join(browser,'public/brand/logo-512.png'),path.join(root,'assets/brand/logo.png'));
await copyFile(path.join(browser,'node_modules/three/LICENSE'),path.join(root,'third_party/licenses/three-LICENSE.txt'));
const glb=await readFile(path.join(root,'reference/source-assets/roadster.glb'));
const gltf=JSON.parse(glb.subarray(20,20+glb.readUInt32LE(12)).toString('utf8'));
const inputs=['src/car.js','src/roads.js','src/track.js','src/main.js','src/props.js','public/models/car.glb','public/brand/logo-512.png','node_modules/three/src/extras/curves/CatmullRomCurve3.js','node_modules/three/src/extras/core/Curve.js'];
const sources=await Promise.all(inputs.map(async p=>({path:p,sha256:createHash('sha256').update(await readFile(path.join(browser,p))).digest('hex')})));
await writeFile(path.join(root,'reference/first-flight.json'),JSON.stringify({captured_utc:new Date().toISOString(),sources,flight_cases:cases.map(({name,frames,dt})=>({name,frames,dt})),flight_frames:rows.length,curve_samples:curveRows.length,track_length:track.length,track_samples:track.n,gltf:{extensionsUsed:gltf.extensionsUsed,extensionsRequired:gltf.extensionsRequired,meshes:gltf.meshes.map(m=>({name:m.name,primitives:m.primitives.length})),nodes:gltf.nodes.map(n=>({name:n.name,mesh:n.mesh})),materials:gltf.materials}},null,2)+'\n');
console.log(`Captured ${rows.length} flight steps, ${curveRows.length} curve samples and ${track.checkpoints.length} gates; copied roadster and logo. Browser files were read only.`);
