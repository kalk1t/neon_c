import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {pathToFileURL} from 'node:url';
const [source,out]=process.argv.slice(2);
if(!source||!out)throw Error('capture-input-state.mjs INPUT_JS OUTPUT_DIRECTORY');
// Pure Input.state oracle: no browser, renderer, network, account or storage.
globalThis.addEventListener=()=>{};
globalThis.document={addEventListener:()=>{}};
let currentPads=[];
Object.defineProperty(globalThis,'navigator',{value:{getGamepads:()=>currentPads},configurable:true});
const {Input}=await import(pathToFileURL(path.resolve(source)));
const input=new Input();
const codes=['KeyW','KeyS','KeyD','ArrowRight','KeyA','ArrowLeft','ArrowUp','ArrowDown','KeyE','KeyQ','ShiftLeft','ShiftRight'];
const profiles=[
 {connected:false,x:1,y:-1,throttle:1,brake:1,boost:true},
 {connected:true,x:0,y:0,throttle:0,brake:0,boost:false},
 {connected:true,x:.149999999,y:-.149999999,throttle:.4,brake:.7,boost:false},
 {connected:true,x:.15,y:-.15,throttle:1,brake:0,boost:true},
 {connected:true,x:-.15,y:.15,throttle:0,brake:1,boost:false},
 {connected:true,x:1,y:-1,throttle:.5,brake:.5,boost:true},
 {connected:true,x:-1,y:1,throttle:.01,brake:.99,boost:false},
 {connected:true,x:.72,y:.33,throttle:.2,brake:.8,boost:false}
];
let rows=[], count=0;
const cases=[];
for(let keys=0;keys<4096;keys++){
  for(const pad of [profiles[0],profiles[1+keys%7]]){
  input.keys=new Set(codes.filter((_,i)=>keys&(1<<i)));
  const buttons=Array.from({length:10},()=>({value:0,pressed:false}));
  buttons[7].value=pad.throttle;buttons[6].value=pad.brake;buttons[0].pressed=pad.boost;
  // A hole before the controller verifies the browser's first-connected rule.
  currentPads=pad.connected?[null,{axes:[pad.x,pad.y],buttons}]:[];
  const s=input.state();
  if(s.keySteer!==(s.steer!==0)||s.keyClimb!==(s.climb!==0))throw Error('Unexpected keyboard aim override semantics');
  const expected=[s.throttle,s.brake,s.steer,s.climb,s.boost];
  rows.push(`{${keys},{${pad.connected},${pad.boost},${pad.x},${pad.y},${pad.throttle},${pad.brake}},{${expected.join(',')}}}`);
  cases.push({keys,pad,expected});count++;
  }
}
fs.mkdirSync(out,{recursive:true});
fs.writeFileSync(path.join(out,'input_state_fixture.h'),'/* Generated by capture-input-state.mjs from actual browser Input.state. */\nstatic const InputCase input_cases[]={\n'+rows.join(',\n')+'\n};\n');
const receipt={source:path.resolve(source),sourceSHA256:crypto.createHash('sha256').update(fs.readFileSync(source)).digest('hex'),caseCount:count,keyboardMasks:4096,padProfiles:profiles,method:'Actual Input.state with inert event registration and navigator gamepad data; no graphics or real devices.',limits:'State mixing only. Native controller mapping/hotplug/input delivery, mouse capture/filtering and hardware latency not validated.'};
fs.writeFileSync(path.join(out,'input-state-oracle.json'),JSON.stringify(receipt,null,2)+'\n');
console.log(JSON.stringify(receipt));
